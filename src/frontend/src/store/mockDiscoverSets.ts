export interface MintMomentSetRank {
  id: string;
  title: string;
  creator: string;
  coverImageUrl: string;
  previewClipUrl?: string;
  description: string;
  totalPacks: number;
  remainingPacks: number;
  pricePerPack: number;
  totalVolume: number;
  salesCount: number;
  nftTrades: number;
  uniqueCollectors: number;
  listedAt: number;
  recentSales: { itemTitle: string; priceUsd: number; timeAgo: string }[];
  // Engagement fields
  packOpens: number;
  previewPlays: number;
  previewReplays: number;
  tapExpansions: number;
  videoCompletionRate: number;
  recentActivityVelocity: number;
  trendingTag: boolean;
}

export function computeEngagementScore(
  set: MintMomentSetRank,
  nowMs: number = Date.now(),
): number {
  const ageMs = nowMs - set.listedAt;
  const ageH = ageMs / 3600000;
  const recencyMult = ageH <= 48 ? 1.5 : ageH <= 168 ? 1.15 : 1.0;

  const base =
    set.packOpens * 12 +
    set.uniqueCollectors * 15 +
    set.previewPlays * 4 +
    set.previewReplays * 8 +
    set.tapExpansions * 5 +
    set.videoCompletionRate * 200 +
    set.recentActivityVelocity * 50 +
    set.salesCount * 6 +
    set.totalVolume * 0.05;

  return base * recencyMult;
}

// Legacy scoring kept for backward compat
export function computeScore(
  set: MintMomentSetRank,
  nowMs: number = Date.now(),
): number {
  return computeEngagementScore(set, nowMs);
}

