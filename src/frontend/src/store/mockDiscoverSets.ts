const TIME_RANGE_MS: Record<string, number> = {
  "24H": 24 * 60 * 60 * 1000,
  "7D": 7 * 24 * 60 * 60 * 1000,
  "30D": 30 * 24 * 60 * 60 * 1000,
};

export function getDiscoverSets(
  timeRange: "ALL_TIME" | "24H" | "7D" | "30D",
): MintMomentSetRank[] {
  const nowMs = Date.now();
  const cutoff =
    timeRange === "ALL_TIME"
      ? null
      : new Date(nowMs - TIME_RANGE_MS[timeRange]);

  const filtered = cutoff
    ? MOCK_DISCOVER_SETS.filter((s) => s.listedAt >= cutoff.getTime())
    : MOCK_DISCOVER_SETS;

  return [...filtered]
    .sort(
      (a, b) =>
        computeEngagementScore(b, nowMs) - computeEngagementScore(a, nowMs),
    )
    .slice(0, 100);
}

export interface DiscoverSections {
  trendingNow: MintMomentSetRank[];
  mostOpened: MintMomentSetRank[];
  risingFast: MintMomentSetRank[];
  mostCollected: MintMomentSetRank[];
  freshMoments: MintMomentSetRank[];
}

export function getDiscoverSections(
  timeRange: "ALL_TIME" | "24H" | "7D" | "30D",
): DiscoverSections {
  const nowMs = Date.now();
  const cutoff =
    timeRange === "ALL_TIME"
      ? null
      : new Date(nowMs - TIME_RANGE_MS[timeRange]);

  const pool = cutoff
    ? MOCK_DISCOVER_SETS.filter((s) => s.listedAt >= cutoff.getTime())
    : MOCK_DISCOVER_SETS;

  const scored = [...pool].sort(
    (a, b) =>
      computeEngagementScore(b, nowMs) - computeEngagementScore(a, nowMs),
  );

  const h72 = nowMs - 72 * 3600000;

  const trendingNow = scored.slice(0, 6);

  const mostOpened = [...pool]
    .sort((a, b) => b.packOpens - a.packOpens)
    .slice(0, 6);

  const risingFast = [...pool]
    .sort((a, b) => {
      const aScore =
        a.recentActivityVelocity * 2 + (a.listedAt >= h72 ? 50 : 0);
      const bScore =
        b.recentActivityVelocity * 2 + (b.listedAt >= h72 ? 50 : 0);
      return bScore - aScore;
    })
    .slice(0, 6);

  const mostCollected = [...pool]
    .sort((a, b) => b.uniqueCollectors - a.uniqueCollectors)
    .slice(0, 6);

  const freshMoments = [...pool]
    .sort((a, b) => b.listedAt - a.listedAt)
    .slice(0, 6);

  return { trendingNow, mostOpened, risingFast, mostCollected, freshMoments };
}
