export interface MintMomentSetRank {
  id: string;
  title: string;
  creator: string;
  coverImageUrl: string;
  previewClipUrl?: string;
  description: string;
  totalPacks: number;
  remainingPacks: number;
  pricePerPack: number;
  totalVolume: number;
  salesCount: number;
  nftTrades: number;
  uniqueCollectors: number;
  listedAt: number;
  recentSales: { itemTitle: string; priceUsd: number; timeAgo: string }[];
}

// Weighted scoring:
// score = (totalVolume * 0.40) + (salesCount * 8 * 0.25) + (nftTrades * 6 * 0.15) + (uniqueCollectors * 10 * 0.15) + (recentBoost * 0.05)
export function computeScore(
  set: MintMomentSetRank,
  nowMs: number = Date.now(),
): number {
  const ageMs = nowMs - set.listedAt;
  const ageH = ageMs / (1000 * 60 * 60);
  const recentBoost = ageH <= 24 ? 1000 : Math.max(0, 1000 - ageH * 3);

  return (
    set.totalVolume * 0.4 +
    set.salesCount * 8 * 0.25 +
    set.nftTrades * 6 * 0.15 +
    set.uniqueCollectors * 10 * 0.15 +
    recentBoost * 0.05
  );
}

