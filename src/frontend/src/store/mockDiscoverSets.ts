const TIME_RANGE_MS: Record<string, number> = {
  "24H": 24 * 60 * 60 * 1000,
  "7D": 7 * 24 * 60 * 60 * 1000,
  "30D": 30 * 24 * 60 * 60 * 1000,
};

export function getDiscoverSets(
  timeRange: "ALL_TIME" | "24H" | "7D" | "30D",
): MintMomentSetRank[] {
  const nowMs = Date.now();
  const cutoff =
    timeRange === "ALL_TIME"
      ? null
      : new Date(nowMs - TIME_RANGE_MS[timeRange]);

  const filtered = cutoff
    ? MOCK_DISCOVER_SETS.filter((s) => s.listedAt >= cutoff.getTime())
    : MOCK_DISCOVER_SETS;

  return [...filtered]
    .sort((a, b) => computeScore(b, nowMs) - computeScore(a, nowMs))
    .slice(0, 100);
}
